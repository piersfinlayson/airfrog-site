"""Airfrog's addresses, from urls.toml.

Usage: python3 ci/urls.py COMMAND
  url NAME [KEY=VALUE ...]   prints entry NAME's full URL
  path NAME [KEY=VALUE ...]  prints entry NAME's path on its host
  write                      writes js/urls.js
  check DIR                  fails when a file in DIR outside the table
                             contains a full address on a host of the table
                             that doesn't have check = false,
                             or when DIR is this site and js/urls.js isn't
                             what write produces

KEY=VALUE fills the entry's {KEY}. Use the Python ci/install-python.sh
installs. Release scripts import url() and path().
"""
import os
import re
import sys
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, 'urls.toml')
GENERATED = os.path.join(ROOT, 'js', 'urls.js')
PLACEHOLDER = re.compile(r'\{([a-z_]+)\}')

# Directories check() doesn't read.
SKIP_DIRS = {'.git', 'build', 'target', '__pycache__', 'node_modules', 'managed_components', 'vendor',
             'tests', 'test'}


def entries():
    with open(TABLE, 'rb') as f:
        return tomllib.load(f)


def fill(text, values):
    names = set(PLACEHOLDER.findall(text))
    missing = names - set(values)
    if missing:
        raise KeyError('%s requires %s' % (text, ', '.join(sorted(missing))))
    return PLACEHOLDER.sub(lambda m: str(values[m.group(1)]), text)


def path(name, **values):
    """Entry name's path on its host, with each {KEY} filled from values."""
    return fill(entries()[name]['path'], values)


def url(name, **values):
    """Entry name's full URL, with each {KEY} filled from values."""
    table = entries()
    entry = table[name]
    if 'url' in entry:
        return entry['url']
    return table[entry['host']]['url'] + fill(entry['path'], values)


def generated():
    """js/urls.js's contents: every entry's full URL, with its placeholders
    unfilled."""
    lines = ['// Generated by ci/urls.py from urls.toml.', '']
    table = entries()
    for name, entry in table.items():
        address = entry['url'] if 'url' in entry else table[entry['host']]['url'] + entry['path']
        lines += ['/** %s */' % entry['comment'], "export const %s = '%s';" % (name, address)]
    return '\n'.join(lines) + '\n'


def write():
    with open(GENERATED, 'w') as f:
        f.write(generated())


def addresses():
    """A full address on each host of the table starts with one of these."""
    return ['//' + entry['url'].split('//', 1)[1].rstrip('/') for entry in entries().values()
            if 'url' in entry and entry.get('check', True)]


def check(directory):
    directory = os.path.abspath(directory)
    hosts = addresses()
    found = []
    for top, dirs, files in os.walk(directory):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
        for file in sorted(files):
            p = os.path.join(top, file)
            if file.endswith('.md') or p in (TABLE, GENERATED):
                continue
            try:
                with open(p, encoding='utf-8') as f:
                    lines = f.readlines()
            except (UnicodeDecodeError, OSError):
                continue
            for number, line in enumerate(lines, 1):
                if any(re.search(re.escape(h) + r'(?![\w.-])', line) for h in hosts):
                    found.append('%s:%d: %s' % (os.path.relpath(p, directory), number, line.strip()))
    if found:
        print('Full addresses outside urls.toml. Use ci/urls.py or js/urls.js:', file=sys.stderr)
        print('\n'.join(found), file=sys.stderr)
    stale = directory == ROOT and open(GENERATED).read() != generated()
    if stale:
        print('js/urls.js differs from urls.toml. Run ci/urls.py write.', file=sys.stderr)
    return not found and not stale


def values(args):
    return dict(arg.split('=', 1) for arg in args)


def main():
    args = sys.argv[1:]
    if args[:1] == ['url'] and len(args) >= 2:
        print(url(args[1], **values(args[2:])))
    elif args[:1] == ['path'] and len(args) >= 2:
        print(path(args[1], **values(args[2:])))
    elif args == ['write']:
        write()
    elif args[:1] == ['check'] and len(args) == 2:
        sys.exit(0 if check(args[1]) else 1)
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main()
